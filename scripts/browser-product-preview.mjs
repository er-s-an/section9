import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const out=new URL('../artifacts/product-ux/20260922/',import.meta.url);
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.S9_PREVIEW_URL||'http://127.0.0.1:9027/');
const jargon=/cost-analysis|CASE BOARD|MONITOR|CONSULT|EXECUTE|VERIFY|分镜|研究用例|非生产|tool_state|synthetic|设计原型/;
for(let i=0;i<6;i++){
 await page.locator('.chapters button').nth(i).click();
 assert.equal(await page.locator('#sceneCount').innerText(),`0${i+1} / 06`);
 assert(!jargon.test(await page.locator('body').innerText()),`engineering copy at step ${i}`);
 assert.equal(await page.locator('.cost').isVisible(),i>=3);
 checks.push(`step ${i+1}: product copy and expert visibility`);
}
await page.locator('.chapters button').nth(2).click();
assert(await page.getByText('正在邀请专家').count());
await page.locator('.chapters button').nth(3).click();
await page.waitForTimeout(1400);
await page.locator('.cost').click();
await page.getByRole('dialog').waitFor({state:'visible'});
assert.equal(await page.locator('#drawerTitle').innerText(),'成本专家');
assert.equal(await page.locator('#drawerStage').innerText(),'专家接单');
await page.keyboard.press('Escape');
assert.equal(await page.locator('#drawer').getAttribute('aria-hidden'),'true');
assert.equal(await page.evaluate(()=>document.activeElement.dataset.role),'cost');
checks.push('expert details, stage, Escape, focus return');
await page.locator('.preview-options summary').click();
await page.locator('#interrupt').click();
assert(await page.locator('#next').isDisabled());
assert(await page.locator('#play').isDisabled());
assert(await page.locator('#dependency').isVisible());
await page.locator('#resume').click();
assert(!(await page.locator('#next').isDisabled()));
await page.locator('#play').click();
await page.locator('.preview-options summary').click();
checks.push('connection pause, frozen controls, resume');
await page.locator('#openEvidence').click();
assert(await page.getByRole('dialog').isVisible());
await page.getByRole('button',{name:'关闭',exact:true}).click();
await page.locator('#evidence details').first().locator('summary').click();
await page.getByRole('button',{name:'查看处理记录 →'}).click();
assert.equal(await page.locator('#drawerTitle').innerText(),'原始客服请求');
await page.keyboard.press('Escape');
await page.locator('#evidence details').first().locator('summary').click();
checks.push('event details and archive record');
for(const width of [1440,1280,390]){
 await page.setViewportSize({width,height:width===390?844:1000});
 await page.locator('.chapters button').nth(3).click();
 await page.waitForTimeout(350);
 await page.evaluate(()=>window.scrollTo(0,0));
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 assert(!overflow,`horizontal overflow ${width}`);
 const controls=await page.locator('#next').boundingBox();
 assert(controls.width>=44&&controls.height>=44);
 await page.screenshot({path:new URL(`preview-after-${width}.png`,out).pathname,fullPage:true});
 checks.push(`layout ${width}: scroll, no overflow, controls`);
}
assert.deepEqual(errors,[]);
await fs.writeFile(new URL('preview-qa.json',out),JSON.stringify({passed:true,scope:'Synthetic interactive preview; no backend or model validation claimed',checks,errors},null,2));
console.log(JSON.stringify({passed:true,checks:checks.length,errors}));
await browser.close();
